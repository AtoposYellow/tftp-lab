"""
TFTP 服务器核心包（《计算机通信与网络》Socket 编程实验）

本包实现了一个严格遵循 RFC 1350 的 TFTP（简单文件传输协议）服务器，
完全基于 Python 标准库的 socket 模块手工构建 UDP 通信逻辑，
不依赖任何现成的 TFTP 组件或第三方封装库。

包内模块划分（自底向上）：
    packets  —— TFTP 五种报文（RRQ/WRQ/DATA/ACK/ERROR）的面向对象编解码；
    netascii —— netascii 传输模式与本地文本之间的流式换行转换器；
    logger   —— 三路日志（彩色控制台 / 滚动文件 / 内存环形缓冲）；
    registry —— 传输会话登记表（供 Web 界面实时展示）；
    stats    —— 吞吐量测量与全局统计；
    session  —— 单次传输会话（RRQ 下载 / WRQ 上传状态机，一线程一会话）；
    server   —— TFTP 服务器主体（69 端口监听、请求分发、并发控制、路径安全）。

协议要点（详见各模块 docstring）：
    * 服务器常驻 UDP 69 端口等待 RRQ/WRQ 请求；
    * 每个请求由一个新线程处理，并通过一个新的临时 UDP 端口（即 TID）与客户端交互；
    * 块号按 16 位回绕（65535 -> 0），因此可支持大于 32 MiB 的文件传输；
    * 超时重传、重复报文处理、末块确认宽限等机制保证异常链路下的可靠传输。
"""

